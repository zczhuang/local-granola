//! `enhance_local`: Granola-style enhanced notes from a local Ollama model.
//!
//! Loads the user's typed note, the transcript words and the participants of a
//! session, runs `enhanced-notes`, and saves the result (with the source hash
//! and generation metadata) into the existing enhanced note document through
//! the same transaction as `save_generated_summary`.

use anlg_enhanced_notes::{
    ChineseScript, EnhanceError, EnhanceInput, EnhanceOptions, EnhanceResult, ExtractClient,
    Metadata, SpeakerLabels, TranscriptInput, Word, compute_hashes,
};
use serde::{Deserialize, Serialize};
use serde_json::Value;
use specta::Type;
use sqlx::SqlitePool;

use crate::generated_summary::{
    GenerationRecord, PendingAutoEnhanceGuard, SaveGeneratedSummaryRequest,
    save_generated_summary_with,
};

const DEFAULT_NUM_CTX: u32 = 32_768;

/// Returned instead of overwriting a summary this engine did not write.
pub const FOREIGN_NOTE_ERROR: &str =
    "this note was not generated by local enhancement; choose Regenerate to replace it";

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, Type)]
pub struct EnhanceLocalRequest {
    pub session_id: String,
    /// The enhanced note document (kind `summary`) to write into.
    pub note_id: String,
    /// Discard manual edits and deletions of AI lines.
    pub regenerate: bool,
    pub owner_user_id: Option<String>,
    pub model: Option<String>,
    pub base_url: Option<String>,
    pub num_ctx: Option<u32>,
    /// `"traditional"` (default) or `"simplified"`.
    pub chinese_script: Option<String>,
    pub pending_auto_enhance: Option<PendingAutoEnhanceGuard>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, Type)]
pub struct EnhanceLocalResponse {
    pub note_id: String,
    pub source_hash: String,
    /// Markdown of the saved document (for title generation).
    pub text: String,
    pub ai_line_count: u32,
    pub kept_edited: u32,
    pub kept_user: u32,
    pub deleted_honored: u32,
    pub chunks: u32,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, Type)]
pub struct EnhanceLocalStaleRequest {
    pub session_id: String,
    pub note_id: String,
}

/// Everything read from the database for one enhancement.
pub struct LoadedInputs {
    pub raw_doc: Value,
    pub transcripts: Vec<TranscriptInput>,
    pub speaker_labels: SpeakerLabels,
    pub participants: Vec<String>,
}

/// True when the note holds content that is not an enhanced-notes record: an
/// old hosted summary or text the user wrote. Blank notes (never enhanced) are not foreign.
fn holds_foreign_content(note: &NoteRow, metadata: &Option<Metadata>) -> bool {
    if metadata.is_some() {
        return false;
    }
    let body = note.body.trim();
    if body.is_empty() {
        return false;
    }
    // An empty ProseMirror document counts as blank.
    if note.body_format == "prosemirror_json"
        && let Ok(doc) = serde_json::from_str::<Value>(body)
        && doc
            .get("content")
            .and_then(Value::as_array)
            .is_none_or(|content| content.is_empty())
    {
        return false;
    }
    true
}

struct NoteRow {
    body: String,
    body_format: String,
    source_hash: String,
    generation_metadata_json: String,
}

fn db_err(error: sqlx::Error) -> String {
    error.to_string()
}

fn empty_doc() -> Value {
    serde_json::json!({"type": "doc", "content": [{"type": "paragraph"}]})
}

fn body_to_doc(body: &str, format: &str) -> Result<Value, String> {
    if body.trim().is_empty() {
        return Ok(empty_doc());
    }
    if format == "markdown" {
        return anlg_tiptap::md_to_tiptap_json(body);
    }
    serde_json::from_str(body).map_err(|error| format!("invalid note document: {error}"))
}

/// Tolerant parse of `transcripts.words_json` (float timestamps, extra fields,
/// missing ids).
pub fn parse_words(words_json: &str) -> Vec<Word> {
    let Ok(Value::Array(items)) = serde_json::from_str::<Value>(words_json) else {
        return Vec::new();
    };
    let millis = |value: Option<&Value>| -> i64 {
        value
            .and_then(|v| v.as_i64().or_else(|| v.as_f64().map(|f| f.round() as i64)))
            .unwrap_or(0)
    };
    let mut words: Vec<Word> = items
        .iter()
        .enumerate()
        .filter_map(|(index, item)| {
            let text = item.get("text")?.as_str()?.to_owned();
            if text.trim().is_empty() {
                return None;
            }
            Some(Word {
                id: item
                    .get("id")
                    .and_then(Value::as_str)
                    .map(str::to_owned)
                    .unwrap_or_else(|| format!("w{index}")),
                text,
                start_ms: millis(item.get("start_ms")),
                end_ms: millis(item.get("end_ms")),
                channel: item.get("channel").and_then(Value::as_i64).unwrap_or(0) as i32,
                speaker_index: item
                    .get("speaker_index")
                    .and_then(Value::as_i64)
                    .map(|v| v as i32),
            })
        })
        .collect();
    words.sort_by_key(|w| (w.start_ms, w.end_ms));
    words
}

async fn load_note_row(
    pool: &SqlitePool,
    session_id: &str,
    note_id: &str,
) -> Result<NoteRow, String> {
    let row: Option<(String, String, String, String)> = sqlx::query_as(
        "SELECT body, body_format, source_hash, generation_metadata_json
         FROM session_documents
         WHERE id = ? AND session_id = ? AND kind IN ('summary', 'template_output')
           AND deleted_at IS NULL",
    )
    .bind(note_id)
    .bind(session_id)
    .fetch_optional(pool)
    .await
    .map_err(db_err)?;
    let (body, body_format, source_hash, generation_metadata_json) =
        row.ok_or_else(|| "enhanced note document not found".to_string())?;
    Ok(NoteRow {
        body,
        body_format,
        source_hash,
        generation_metadata_json,
    })
}

pub async fn load_inputs(pool: &SqlitePool, session_id: &str) -> Result<LoadedInputs, String> {
    let raw: Option<(String, String)> = sqlx::query_as(
        "SELECT body, body_format FROM session_documents
         WHERE session_id = ? AND kind = 'note' AND deleted_at IS NULL
         ORDER BY sort_order, created_at LIMIT 1",
    )
    .bind(session_id)
    .fetch_optional(pool)
    .await
    .map_err(db_err)?;
    let raw_doc = match raw {
        Some((body, format)) => body_to_doc(&body, &format)?,
        None => empty_doc(),
    };

    let rows: Vec<(String, String)> = sqlx::query_as(
        "SELECT id, words_json FROM transcripts
         WHERE session_id = ? AND deleted_at IS NULL
         ORDER BY started_at_ms, created_at, id",
    )
    .bind(session_id)
    .fetch_all(pool)
    .await
    .map_err(db_err)?;
    let transcripts = rows
        .into_iter()
        .map(|(id, words_json)| TranscriptInput {
            transcript_id: id,
            words: parse_words(&words_json),
        })
        .filter(|transcript| !transcript.words.is_empty())
        .collect();

    let names: Vec<(String,)> = sqlx::query_as(
        "SELECT COALESCE(NULLIF(trim(p.display_name), ''), NULLIF(trim(h.name), ''), '')
         FROM session_participants p
         LEFT JOIN humans h ON h.id = p.human_id AND h.deleted_at IS NULL
         WHERE p.session_id = ? AND p.deleted_at IS NULL
         ORDER BY p.created_at, p.id",
    )
    .bind(session_id)
    .fetch_all(pool)
    .await
    .map_err(db_err)?;
    let mut participants: Vec<String> = Vec::new();
    for (name,) in names {
        if !name.is_empty() && !participants.contains(&name) {
            participants.push(name);
        }
    }

    // Speaker labels default to "You" (mic) and "Speaker N"; the model also
    // receives the participant names separately.
    Ok(LoadedInputs {
        raw_doc,
        transcripts,
        speaker_labels: SpeakerLabels::default(),
        participants,
    })
}

fn chinese_script(value: Option<&str>) -> ChineseScript {
    match value {
        Some("simplified") => ChineseScript::Simplified,
        _ => ChineseScript::Traditional,
    }
}

/// A finished enhancement, not yet saved. `note` is the enhanced document as
/// it was when the model started; the save fails if it changed meanwhile.
pub struct Computed {
    note: NoteRow,
    result: EnhanceResult,
}

/// Run the engine against `client` (no writes). Generic over the client so
/// tests can script the model.
pub async fn compute<C: ExtractClient>(
    pool: &SqlitePool,
    request: &EnhanceLocalRequest,
    client: &C,
) -> Result<Computed, String> {
    let note = load_note_row(pool, &request.session_id, &request.note_id).await?;
    let inputs = load_inputs(pool, &request.session_id).await?;

    let prev_metadata = Metadata::from_json_str(&note.generation_metadata_json);
    if !request.regenerate && holds_foreign_content(&note, &prev_metadata) {
        return Err(FOREIGN_NOTE_ERROR.to_string());
    }
    let prev_doc = (note.body_format == "prosemirror_json" && prev_metadata.is_some())
        .then(|| serde_json::from_str::<Value>(&note.body).ok())
        .flatten();

    let num_ctx = request.num_ctx.unwrap_or(DEFAULT_NUM_CTX).max(2048) as usize;
    let result = anlg_enhanced_notes::enhance(
        EnhanceInput {
            raw_doc: inputs.raw_doc,
            transcripts: inputs.transcripts,
            speaker_labels: inputs.speaker_labels,
            participants: inputs.participants,
            prev_doc,
            prev_metadata,
            regenerate: request.regenerate,
            options: EnhanceOptions {
                num_ctx,
                chinese_script: chinese_script(request.chinese_script.as_deref()),
            },
        },
        client,
    )
    .await
    .map_err(|error: EnhanceError| error.to_string())?;

    Ok(Computed { note, result })
}

#[cfg(test)]
pub async fn enhance_and_save<C: ExtractClient>(
    pool: &SqlitePool,
    request: EnhanceLocalRequest,
    client: &C,
) -> Result<EnhanceLocalResponse, String> {
    let computed = compute(pool, &request, client).await?;
    save_computed(pool, &request, computed).await
}

pub async fn save_computed(
    pool: &SqlitePool,
    request: &EnhanceLocalRequest,
    computed: Computed,
) -> Result<EnhanceLocalResponse, String> {
    let Computed { note, result } = computed;
    let note = &note;
    let text = anlg_tiptap::tiptap_json_to_md(&result.doc).unwrap_or_default();
    let next_body = serde_json::to_string(&result.doc).map_err(|error| error.to_string())?;
    let metadata_json =
        serde_json::to_string(&result.metadata).map_err(|error| error.to_string())?;
    save_generated_summary_with(
        pool,
        SaveGeneratedSummaryRequest {
            session_id: request.session_id.clone(),
            owner_user_id: request.owner_user_id.clone().unwrap_or_default(),
            note_id: request.note_id.clone(),
            current_body: note.body.clone(),
            current_body_format: note.body_format.clone(),
            next_body,
            tag_names: Vec::new(),
            title: None,
            pending_auto_enhance: request.pending_auto_enhance.clone(),
        },
        Some(GenerationRecord {
            source_hash: &result.source_hash,
            generation_metadata_json: &metadata_json,
        }),
    )
    .await?;

    Ok(EnhanceLocalResponse {
        note_id: request.note_id.clone(),
        source_hash: result.source_hash,
        text,
        ai_line_count: result.metadata.ai_lines.len() as u32,
        kept_edited: result.stats.kept_edited as u32,
        kept_user: result.stats.kept_user as u32,
        deleted_honored: result.stats.deleted_honored as u32,
        chunks: result.chunks as u32,
    })
}

pub async fn compute_with_ollama(
    pool: &SqlitePool,
    request: &EnhanceLocalRequest,
) -> Result<Computed, String> {
    let model = request
        .model
        .clone()
        .filter(|m| !m.trim().is_empty())
        .unwrap_or_else(|| anlg_enhanced_notes::ollama::DEFAULT_MODEL.to_string());
    let base_url = request
        .base_url
        .clone()
        .filter(|u| !u.trim().is_empty())
        .unwrap_or_else(|| anlg_enhanced_notes::ollama::DEFAULT_BASE_URL.to_string());
    let num_ctx = request.num_ctx.unwrap_or(DEFAULT_NUM_CTX).max(2048) as usize;
    let client = anlg_enhanced_notes::ollama::OllamaClient::new(&base_url, &model, num_ctx)
        .map_err(|error| error.to_string())?;
    compute(pool, request, &client).await
}

/// True when the saved enhanced note was generated from different typed notes
/// or transcript than the session currently has (or has never been enhanced).
pub async fn is_stale(
    pool: &SqlitePool,
    request: &EnhanceLocalStaleRequest,
) -> Result<bool, String> {
    let note = load_note_row(pool, &request.session_id, &request.note_id).await?;
    let inputs = load_inputs(pool, &request.session_id).await?;
    if inputs.transcripts.is_empty() {
        return Ok(false);
    }
    // Old hosted summaries and hand-written notes carry no enhanced-notes metadata; never
    // auto-refresh them (only an explicit Regenerate may replace them).
    let metadata = Metadata::from_json_str(&note.generation_metadata_json);
    if holds_foreign_content(&note, &metadata) {
        return Ok(false);
    }
    let (_, _, source_hash) = compute_hashes(&inputs.raw_doc, &inputs.transcripts);
    Ok(note.source_hash != source_hash)
}

#[cfg(test)]
mod tests {
    use super::*;
    use anlg_db_core::Db;
    use anlg_enhanced_notes::{EnhanceOutput, schema::Bullet, schema::Section};
    use serde_json::json;

    struct Scripted(EnhanceOutput);

    impl ExtractClient for Scripted {
        fn model_name(&self) -> String {
            "scripted".into()
        }
        async fn extract(
            &self,
            _system: &str,
            _user: &str,
            _schema: &Value,
        ) -> Result<EnhanceOutput, EnhanceError> {
            Ok(self.0.clone())
        }
    }

    async fn db() -> Db {
        let db = Db::connect_memory_plain().await.unwrap();
        anlg_db_app::prepare_schema(&db).await.unwrap();
        sqlx::query("INSERT INTO sessions (id, workspace_id, owner_user_id) VALUES ('s1','w','u')")
            .execute(db.pool())
            .await
            .unwrap();
        let note = json!({"type":"doc","content":[{"type":"paragraph","content":[{"type":"text","text":"Pricing"}]}]});
        sqlx::query("INSERT INTO session_documents (id, workspace_id, session_id, kind, body, body_format) VALUES ('raw','w','s1','note',?,'prosemirror_json')")
            .bind(note.to_string()).execute(db.pool()).await.unwrap();
        sqlx::query("INSERT INTO session_documents (id, workspace_id, session_id, kind, body, body_format) VALUES ('enh','w','s1','summary','','markdown')")
            .execute(db.pool()).await.unwrap();
        let words = json!([
            {"id":"w1","text":"The","start_ms":0.0,"end_ms":100.4,"channel":0,"state":"final"},
            {"id":"w2","text":"starter","start_ms":100,"end_ms":300,"channel":0},
            {"id":"w3","text":"plan","start_ms":300,"end_ms":500,"channel":0},
            {"id":"w4","text":"costs","start_ms":500,"end_ms":700,"channel":0},
            {"id":"w5","text":"ten","start_ms":700,"end_ms":900,"channel":0},
            {"id":"w6","text":"dollars","start_ms":900,"end_ms":1200,"channel":0},
        ]);
        sqlx::query("INSERT INTO transcripts (id, workspace_id, session_id, words_json, started_at_ms) VALUES ('t1','w','s1',?,0)")
            .bind(words.to_string()).execute(db.pool()).await.unwrap();
        db
    }

    fn request() -> EnhanceLocalRequest {
        EnhanceLocalRequest {
            session_id: "s1".into(),
            note_id: "enh".into(),
            regenerate: false,
            owner_user_id: None,
            model: None,
            base_url: None,
            num_ctx: None,
            chinese_script: None,
            pending_auto_enhance: None,
        }
    }

    #[test]
    fn words_parse_tolerantly() {
        let words = parse_words(
            r#"[{"id":"a","text":"hi","start_ms":10.6,"end_ms":20},{"text":" "},{"text":"x"}]"#,
        );
        assert_eq!(words.len(), 2);
        // Sorted by start time: the id-less word with no timestamps is first.
        assert_eq!(words[0].id, "w2");
        assert_eq!(words[1].start_ms, 11);
        assert!(parse_words("not json").is_empty());
    }

    #[tokio::test]
    async fn enhance_saves_doc_hash_and_metadata_then_is_fresh() {
        let db = db().await;
        let stale_request = EnhanceLocalStaleRequest {
            session_id: "s1".into(),
            note_id: "enh".into(),
        };
        assert!(is_stale(db.pool(), &stale_request).await.unwrap());

        let client = Scripted(EnhanceOutput {
            sections: vec![Section {
                anchor: "a1".into(),
                bullets: vec![Bullet {
                    text: "Starter plan costs ten dollars".into(),
                    sources: vec!["s1".into()],
                }],
            }],
            ..Default::default()
        });
        let response = enhance_and_save(db.pool(), request(), &client)
            .await
            .unwrap();
        assert_eq!(response.ai_line_count, 1);
        assert!(response.text.contains("Pricing"));

        let (body, format, hash, meta): (String, String, String, String) = sqlx::query_as(
            "SELECT body, body_format, source_hash, generation_metadata_json FROM session_documents WHERE id = 'enh'",
        )
        .fetch_one(db.pool())
        .await
        .unwrap();
        assert_eq!(format, "prosemirror_json");
        assert_eq!(hash, response.source_hash);
        assert!(body.contains("\"aiId\""));
        assert!(Metadata::from_json_str(&meta).is_some());
        assert!(!is_stale(db.pool(), &stale_request).await.unwrap());

        // Editing the typed note makes it stale again.
        let edited = json!({"type":"doc","content":[{"type":"paragraph","content":[{"type":"text","text":"Pricing and rollout"}]}]});
        sqlx::query("UPDATE session_documents SET body = ? WHERE id = 'raw'")
            .bind(edited.to_string())
            .execute(db.pool())
            .await
            .unwrap();
        assert!(is_stale(db.pool(), &stale_request).await.unwrap());

        // Re-enhancing works on the saved enhanced doc (second save passes the
        // optimistic body check).
        let again = enhance_and_save(db.pool(), request(), &client)
            .await
            .unwrap();
        assert_ne!(again.source_hash, response.source_hash);
    }

    #[tokio::test]
    async fn missing_transcript_is_an_error() {
        let db = db().await;
        sqlx::query("DELETE FROM transcripts")
            .execute(db.pool())
            .await
            .unwrap();
        let client = Scripted(EnhanceOutput::default());
        let error = enhance_and_save(db.pool(), request(), &client)
            .await
            .unwrap_err();
        assert!(error.contains("transcript"), "{error}");
    }

    #[tokio::test]
    async fn foreign_summaries_are_never_stale_or_replaced_without_regenerate() {
        let db = db().await;
        sqlx::query(
            "UPDATE session_documents SET body = '## Old hosted summary', body_format = 'markdown', source_hash = 'old' WHERE id = 'enh'",
        )
        .execute(db.pool())
        .await
        .unwrap();
        let stale_request = EnhanceLocalStaleRequest {
            session_id: "s1".into(),
            note_id: "enh".into(),
        };
        assert!(!is_stale(db.pool(), &stale_request).await.unwrap());

        let client = Scripted(EnhanceOutput::default());
        let error = enhance_and_save(db.pool(), request(), &client)
            .await
            .unwrap_err();
        assert_eq!(error, FOREIGN_NOTE_ERROR);
        let (body,): (String,) =
            sqlx::query_as("SELECT body FROM session_documents WHERE id = 'enh'")
                .fetch_one(db.pool())
                .await
                .unwrap();
        assert_eq!(body, "## Old hosted summary");

        // An explicit Regenerate may replace it.
        let regenerate = EnhanceLocalRequest {
            regenerate: true,
            ..request()
        };
        enhance_and_save(db.pool(), regenerate, &client)
            .await
            .unwrap();
        let (format,): (String,) =
            sqlx::query_as("SELECT body_format FROM session_documents WHERE id = 'enh'")
                .fetch_one(db.pool())
                .await
                .unwrap();
        assert_eq!(format, "prosemirror_json");
    }

    #[test]
    fn blank_notes_are_not_foreign() {
        let row = |body: &str, format: &str| NoteRow {
            body: body.into(),
            body_format: format.into(),
            source_hash: String::new(),
            generation_metadata_json: String::new(),
        };
        assert!(!holds_foreign_content(&row("", "markdown"), &None));
        assert!(!holds_foreign_content(
            &row(r#"{"type":"doc","content":[]}"#, "prosemirror_json"),
            &None
        ));
        assert!(holds_foreign_content(&row("text", "markdown"), &None));
    }
}
